/**
 * Writes the hand-free SVG icon sources from the shared brand mark (src/ui/art/brandMark.tsx):
 *   public/icon.svg          transparent, 512 viewBox (favicon.svg, title screen reference)
 *   public/icon-rounded.svg  sky-blue rounded square (home-screen / PWA variant)
 *   public/wordmark.svg      the mark on a 380 × 160 strip
 * Run: npx vite-node scripts/build-icon-svg.tsx   (then node scripts/build-icons.mjs for the rasters)
 */
import { renderToStaticMarkup } from 'react-dom/server';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { ART, BRAND_MARK_BBOX, BRAND_MARK_LABEL, BrandMarkContent } from '../src/ui/art';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const inner = renderToStaticMarkup(<BrandMarkContent />);
const b = BRAND_MARK_BBOX;
const cx = (b.x0 + b.x1) / 2;
const cy = (b.y0 + b.y1) / 2;
const header = '<!-- Q11 Emergency — Quantum Emergency Response. Original mark built from the game\'s own art (fire truck, flame, smoke), MIT. Generated by scripts/build-icon-svg.tsx from src/ui/art/brandMark.tsx; do not edit by hand. -->';
const icon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512" role="img" aria-label="${BRAND_MARK_LABEL}">\n  ${header}\n  ${inner}\n</svg>\n`;
const rounded = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512" role="img" aria-label="${BRAND_MARK_LABEL}, on a sky-blue rounded square">\n  ${header}\n  <rect width="512" height="512" rx="113" ry="113" fill="${ART.sky}"/>\n  <g transform="translate(256 256) scale(0.84) translate(${String(-cx)} ${String(-cy)})">${inner}</g>\n</svg>\n`;
const wordmark = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 380 160" width="380" height="160" role="img" aria-label="Q11 Emergency">\n  ${header}\n  <g transform="translate(190 80) scale(0.42) translate(${String(-cx)} ${String(-cy)})">${inner}</g>\n</svg>\n`;
writeFileSync(path.join(root, 'public/icon.svg'), icon);
writeFileSync(path.join(root, 'public/icon-rounded.svg'), rounded);
writeFileSync(path.join(root, 'public/wordmark.svg'), wordmark);
console.log('[build-icon-svg] wrote public/icon.svg, icon-rounded.svg, wordmark.svg');
