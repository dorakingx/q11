#!/usr/bin/env node
/**
 * build:qollab — bundles the game for Qollab and assembles the qollab/ project folder.
 *  1. vite build -c vite.qollab.config.ts  → dist-qollab/q11-game.js (+ .css)
 *  2. copy bundle → qollab/game/q11-game.js ; write qollab/main.css = base styles + bundle css
 *  3. sync fixtures → qollab/q11/data (scripts/sync-qollab-data.mjs)
 *  4. enforce Qollab limits: ≤100 files, each ≤ 2 MB; print a manifest with sizes + sha256 to reports/qollab-manifest.json
 */
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, statSync, copyFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const run = (cmd, args) => { const r = spawnSync(cmd, args, { cwd: root, stdio: 'inherit' }); if (r.status !== 0) process.exit(r.status ?? 1); };

run('npx', ['vite', 'build', '-c', 'vite.qollab.config.ts']);
mkdirSync(path.join(root, 'qollab/game'), { recursive: true });
copyFileSync(path.join(root, 'dist-qollab/q11-game.js'), path.join(root, 'qollab/game/q11-game.js'));

const baseCss = existsSync(path.join(root, 'qollab/main.base.css')) ? readFileSync(path.join(root, 'qollab/main.base.css'), 'utf8') : '';
const bundleCss = existsSync(path.join(root, 'dist-qollab/q11-game.css')) ? readFileSync(path.join(root, 'dist-qollab/q11-game.css'), 'utf8') : '';
writeFileSync(path.join(root, 'qollab/main.css'), `/* Q11 — generated by scripts/build-qollab.mjs; edit qollab/main.base.css and src/ui styles instead */\n${baseCss}\n${bundleCss}\n`);

run('node', ['scripts/sync-qollab-data.mjs']);

// Limits + manifest
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = path.join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) { if (name !== '__pycache__') walk(p); }
    else if (!name.endsWith('.pyc')) files.push({ path: path.relative(path.join(root, 'qollab'), p), bytes: st.size, sha256: createHash('sha256').update(readFileSync(p)).digest('hex') });
  }
})(path.join(root, 'qollab'));
const tooBig = files.filter((f) => f.bytes > 2 * 1024 * 1024);
const manifest = { generatedAt: new Date().toISOString(), fileCount: files.length, totalBytes: files.reduce((a, f) => a + f.bytes, 0), files, withinLimits: files.length <= 100 && tooBig.length === 0 };
mkdirSync(path.join(root, 'reports'), { recursive: true });
writeFileSync(path.join(root, 'reports/qollab-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(`[build:qollab] ${files.length} files, ${(manifest.totalBytes / 1024).toFixed(0)} KiB, withinLimits=${manifest.withinLimits}`);
if (!manifest.withinLimits) process.exit(1);
